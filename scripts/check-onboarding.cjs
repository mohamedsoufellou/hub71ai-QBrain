/* Synthetic data only. Run with node scripts/check-onboarding.cjs. */
/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require("node:assert/strict");
const fs = require("node:fs");
const ts = require("typescript");
require.extensions[".ts"] = (module, filename) => {
  module._compile(ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, filename);
};
const { analyseApplicant, demoPartners, emptyApplicant, rankPartners, sampleApplicant, validateApplicant } = require("../lib/onboarding.ts");
const today = new Date("2026-10-02T12:00:00Z");
const sample = sampleApplicant("Sample Person");
const result = analyseApplicant(sample, today);
assert.equal(validateApplicant(sample), null);
assert.equal(result.completeness, 100);
assert.equal(result.partners.length, demoPartners.length);
assert.equal(new Set(result.partners.map((partner) => partner.id)).size, demoPartners.length);
assert(result.partners.every((partner) => partner.score >= 0 && partner.score <= 100));
assert(result.partners.every((partner, index) => index === 0 || result.partners[index - 1].score >= partner.score));
assert(result.nextSteps.some((step) => step.includes("120,000")));
assert(result.nextSteps.some((step) => step.includes("2 person(s)")));
assert.equal(analyseApplicant(emptyApplicant(), today).completeness, 0);
const noDocuments = analyseApplicant({ ...sample, passport: null, cv: null }, today);
assert.equal(noDocuments.completeness, 50);
assert(noDocuments.nextSteps.some((step) => step.includes("passport")));
assert(noDocuments.nextSteps.some((step) => step.includes("CV")));
assert.equal(analyseApplicant({ ...sample, passportExpiry: "2026-09-01" }, today).passportFlag, "Passport expiry date has passed");
assert.equal(analyseApplicant({ ...sample, passportExpiry: "2027-01-01" }, today).completeness, 75);
const dubai = rankPartners({ ...sample, emirate: "Dubai" });
assert.equal(dubai.find((partner) => partner.id === "shore").recommended, false);
assert(dubai.find((partner) => partner.id === "shore").score < result.partners.find((partner) => partner.id === "shore").score);
const founder = rankPartners({ ...sample, employment: "Founder / self-employed", goals: ["Business setup"] });
assert.equal(founder[0].category, "Business");
assert(founder.filter((partner) => partner.recommended).every((partner) => partner.category === "Business"));
assert.equal(validateApplicant({ ...sample, nationality: " " }).step, 0);
assert.equal(validateApplicant({ ...sample, experience: -1 }).step, 2);
assert.equal(validateApplicant({ ...sample, description: "short" }).step, 2);
for (const change of [{ salary: -1 }, { housingBudget: 0 }, { housingBudget: Infinity }, { dependants: 1.5 }, { bedrooms: 10 }, { goals: [] }]) assert.equal(validateApplicant({ ...sample, ...change }).step, 3);

const stored = new Map();
global.sessionStorage = { getItem: (key) => stored.get(key) ?? null, setItem: (key, value) => stored.set(key, value), removeItem: (key) => stored.delete(key) };
const storePath = require.resolve("../lib/onboarding-store.ts");
const { useOnboarding } = require(storePath);
useOnboarding.getState().save("account-a", sample);
useOnboarding.getState().finish("account-a");
useOnboarding.getState().togglePartner("account-a", "studio");
useOnboarding.getState().save("account-b", sampleApplicant("Second Person"));
assert.equal(useOnboarding.getState().applicants["account-b"].name, "Second Person");
assert.equal(useOnboarding.getState().completed["account-a"], true);
assert.deepEqual(useOnboarding.getState().saved["account-a"], ["studio"]);
assert.equal(useOnboarding.getState().saved["account-b"], undefined);
assert(!stored.get("wusool-demo-onboarding").includes("fileContents"));
delete require.cache[storePath];
const restored = require(storePath).useOnboarding;
restored.persist.rehydrate();
assert.equal(restored.getState().completed["account-a"], true);
assert.equal(restored.getState().applicants["account-a"].name, "Sample Person");
restored.getState().save("account-a", { ...sample, emirate: "Dubai" });
assert.equal(restored.getState().completed["account-a"], false, "Editing requires re-analysis");
restored.getState().togglePartner("account-a", "studio");
assert.deepEqual(restored.getState().saved["account-a"], []);
console.log("PASS profile validation, document gaps, expiry flags, partner rankings, emirate and goal changes, per-account persistence and re-analysis");
